import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder
from sklearn.pipeline import make_pipeline
from sklearn.ensemble import RandomForestRegressor

data = pd.DataFrame({
    'Year':[2018,2020,2017,2022,2019,2021],
    'Mileage':[40000,20000,60000,10000,35000,15000],
    'Fuel':['Petrol','Diesel','Petrol','Electric','Diesel','Petrol'],
    'Price':[600000,900000,450000,1500000,700000,1100000]
})

X, y = data.drop('Price',axis=1), data['Price']
prep = ColumnTransformer([('fuel',OneHotEncoder(handle_unknown='ignore'),['Fuel'])],
                         remainder='passthrough')
model = make_pipeline(prep,RandomForestRegressor(random_state=42)).fit(X,y)

print("Predicted Price:", model.predict(pd.DataFrame({
    'Year':[2021],'Mileage':[25000],'Fuel':['Petrol']}))[0])

